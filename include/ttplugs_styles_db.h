static inline const char *ttmm_genre_name(int genre) {
    if (genre < 0 || genre >= TTMM_GENRE_COUNT) return "All";
    return ttmm_genres[genre];
}

static inline const ttmm_preset_def *ttmm_preset_find(const char *name) {
    if (!name || !*name) return 0;
    for (int i = 0; i < TTMM_PRESET_COUNT; i++) {
        if (!strcmp(ttmm_presets[i].name, name)) return &ttmm_presets[i];
    }
    return 0;
}

static inline int ttmm_preset_matches_genre(const char *name, int genre) {
    if (genre <= 0 || !name || !*name) return 1;
    for (int i = 0; i < TTMM_PRESET_COUNT; i++) {
        if (!strcmp(ttmm_presets[i].name, name)) return (ttmm_presets[i].genre == genre);
    }
    return 1;
}

